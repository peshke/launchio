    private void backdropMode(boolean backdrop) {
        if (!backdropLayer) return;
        View scrim = findViewById(R.id.heroScrim);
        scrim.animate().cancel();
        if (animations) scrim.animate().alpha(backdrop ? 1f : 0f).setDuration(300).start();
        else scrim.setAlpha(backdrop ? 1f : 0f);
        if (backdrop && ambientGlow) {
            ambient.animate().cancel();
            if (animations) ambient.animate().alpha(0f).setDuration(300).start();
            else ambient.setAlpha(0f);
        }
    }

    private void showFeatured(int i) {
        if (featured.isEmpty()) return;
        int n = featured.size();
        featuredIndex = ((i % n) + n) % n;
        Featured.Item it = featured.get(featuredIndex);
        heroName.setText(it.title);
        heroName.setVisibility(View.VISIBLE);
        heroLogo.setVisibility(View.GONE);
        heroLogo.setImageDrawable(null);
        heroLogo.setTag(it.logo);
        if (heroLogos && it.logo != null) showLogo(it.logo);
        String facts = !it.resume ? it.facts : TextUtils.isEmpty(it.facts) ? getString(R.string.continue_watching)
                : getString(R.string.continue_watching) + "  ·  " + it.facts;
        heroMeta.setText(facts);
        heroMeta.setVisibility(TextUtils.isEmpty(facts) ? View.GONE : View.VISIBLE);
        heroDesc.setText(it.description);
        heroDesc.setVisibility(TextUtils.isEmpty(it.description) ? View.GONE : View.VISIBLE);
        heroOpen.setText("▶  " + (it.resume ? getString(R.string.resume) : getString(R.string.open_in, openInLabel())));
        hero.post(this::placeHero);   // the blurb's height changes with the title
        showBackdrop(it.backdrop);
        scheduleFeatured();
    }

    /** The logo takes the name's place once it has loaded; a title without one keeps its name. */
    private void showLogo(String url) {
        images.load(url, (int) (420 * density), true, bm -> {
            if (!url.equals(heroLogo.getTag())) return;
            int[] px = new int[bm.getWidth() * bm.getHeight()];
            bm.getPixels(px, 0, bm.getWidth(), 0, 0, bm.getWidth(), bm.getHeight());
            // A dark logo is drawn white, its shape kept.
            if (Featured.dark(px)) heroLogo.setColorFilter(0xFFFFFFFF, android.graphics.PorterDuff.Mode.SRC_IN);
            else heroLogo.clearColorFilter();
            heroLogo.setImageBitmap(bm);
            heroLogo.setVisibility(View.VISIBLE);
            heroName.setVisibility(View.GONE);
            hero.post(this::placeHero);
        });
    }

