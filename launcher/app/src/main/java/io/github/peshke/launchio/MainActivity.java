    private void placeHero() {
        if (lastDockTop <= 0) return;
        float y = lastDockTop - 14 * density - 26 * density - hero.getHeight();
        // Too tall to fit under the clock (a long blurb with the dock lifted): this title goes without its blurb.
        Rect clock = new Rect(0, 0, 0, clockBlock.getHeight());
        root.offsetDescendantRectToMyCoords(clockBlock, clock);
        if (!featured.isEmpty() && heroDesc.getVisibility() == View.VISIBLE && y < clock.bottom + 8 * density) {
            heroDesc.setVisibility(View.GONE);
            hero.post(this::placeHero);
            return;
        }
        hero.setY(y);
    }

    private void showBackdrop(String url) {
        heroArt.setTag(url);
        images.load(url, getResources().getDisplayMetrics().widthPixels / 2, false, bm -> {
            if (started && url.equals(heroArt.getTag())) swapBackdrop(bm);
        });
    }

    private void swapBackdrop(Bitmap bm) {
        float shown = heroShown || cardFocused ? 1f : 0f;
        heroArt.animate().cancel();
        if (!animations || heroArt.getDrawable() == null) {
            heroArt.setImageBitmap(bm);
            heroArt.setAlpha(shown);
            return;
        }
        heroArt.animate().alpha(0f).setDuration(200).withEndAction(() -> {
            heroArt.setImageBitmap(bm);
            heroArt.animate().alpha(shown).setDuration(500).start();
        }).start();
    }

    /** Resume where the app left off, or open the recommendation's page in Nuvio. */
    private void openFeatured() {
        if (!featured.isEmpty()) openItem(featured.get(featuredIndex));
    }

    private void openItem(Featured.Item it) {
        try {
            if (it.resume) {
                Intent resume = it.intentUri == null ? null : Intent.parseUri(it.intentUri, Intent.URI_INTENT_SCHEME);
                if (resume != null) {
                    // The row comes from another app: only ever start that app with it.
                    resume.setPackage(it.pkg);
                    resume.setSelector(null);
                    resume.setFlags(Intent.FLAG_ACTIVITY_NEW_TASK);   // drops any URI grants the row asked for
                    startActivity(resume);
                } else {
                    Intent app = getPackageManager().getLeanbackLaunchIntentForPackage(it.pkg);
                    if (app == null) throw new ActivityNotFoundException();
                    startActivity(app);
                }
            } else {
                Intent page = new Intent(Intent.ACTION_VIEW,
                        Uri.parse("nuvio://meta?type=" + Uri.encode(it.type) + "&id=" + Uri.encode(it.id)));
                page.setPackage(getString(R.string.open_in_package));
                startActivity(page.addFlags(Intent.FLAG_ACTIVITY_NEW_TASK));
            }
        } catch (Exception e) {   // a stale row, a bad intent, or Nuvio not installed
            Toast.makeText(this, R.string.not_available, Toast.LENGTH_SHORT).show();
        }
    }

    private String openInLabel() {
        try {
            return String.valueOf(getPackageManager().getApplicationLabel(
                    getPackageManager().getApplicationInfo(getString(R.string.open_in_package), 0)));
        } catch (Exception e) {
            return "Nuvio";
        }
    }

